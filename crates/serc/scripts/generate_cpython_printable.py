#!/usr/bin/env python3
"""Generate printable-character ranges from the pinned CPython source trees."""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
from pathlib import Path

TARGETS = (
    ("3.12.14", "2abcf904b8dac8c999d2b3aac76681abb333798a"),
    ("3.13.15", "4061bc4c35f7c26f25264666d4ba083b93d2f6f9"),
    ("3.14.5", "5607950ef232dad16d75c0cf53101d9649d89115"),
    ("3.15.0rc2", "435c9e5a798c99653e3ab64ce29baed0e4f3dfee"),
)


def values(source, name):
    match = re.search(rf"{name}\[\]\s*=\s*\{{(.*?)\n\}};", source, re.S)
    if not match:
        raise ValueError(f"missing {name}")
    return [int(value) for value in re.findall(r"\d+", match.group(1))]


def printable_data(path, version, commit):
    actual = subprocess.check_output(
        ["git", "-C", str(path), "rev-parse", "HEAD"], text=True
    ).strip()
    if actual != commit:
        raise ValueError(
            f"{path}: expected CPython {version} at {commit}, got {actual}"
        )
    subprocess.run(
        [
            "git",
            "-C",
            str(path),
            "diff",
            "--quiet",
            "HEAD",
            "--",
            "Objects/unicodetype_db.h",
            "Objects/unicodectype.c",
        ],
        check=True,
    )
    header = (path / "Objects/unicodetype_db.h").read_bytes()
    source = header.decode("ascii")
    type_table = re.search(
        r"_PyUnicode_TypeRecords\[\]\s*=\s*\{(.*?)\n\};", source, re.S
    )
    if not type_table:
        raise ValueError(f"{path}: missing Unicode type records")
    records = [
        tuple(map(int, row.split(",")))
        for row in re.findall(r"\{([^{}]+)\}", type_table.group(1))
    ]
    if any(len(record) != 6 for record in records):
        raise ValueError(f"{path}: unexpected Unicode type record")
    shift_match = re.search(r"^#define SHIFT (\d+)$", source, re.M)
    if not shift_match:
        raise ValueError(f"{path}: missing Unicode table shift")
    shift = int(shift_match.group(1))
    index1, index2 = values(source, "index1"), values(source, "index2")
    mask_source = (path / "Objects/unicodectype.c").read_text("ascii")
    if not re.search(r"^#define PRINTABLE_MASK 0x400$", mask_source, re.M):
        raise ValueError(f"{path}: unexpected printable mask")
    bits = bytearray(0x110000)
    for codepoint in range(len(bits)):
        index = index2[
            (index1[codepoint >> shift] << shift) + (codepoint & ((1 << shift) - 1))
        ]
        bits[codepoint] = bool(records[index][5] & 0x400)
    return bits, hashlib.sha256(header).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "sources",
        nargs=4,
        type=Path,
        help="CPython source trees for 3.12, 3.13, 3.14, and 3.15",
    )
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    inputs = [
        printable_data(path, *target)
        for path, target in zip(args.sources, TARGETS, strict=True)
    ]
    merged = bytearray(0x110000)
    for target_index, (bits, _) in enumerate(inputs):
        for codepoint, bit in enumerate(bits):
            merged[codepoint] |= bit << target_index
    ranges = []
    start, previous = 0, merged[0]
    for codepoint, mask in enumerate(merged[1:], 1):
        if mask != previous:
            if previous:
                ranges.append((start, codepoint - 1, previous))
            start, previous = codepoint, mask
    if previous:
        ranges.append((start, len(merged) - 1, previous))

    lines = ["// @generated by scripts/generate_cpython_printable.py; do not edit."]
    for (version, commit), (_, sha256) in zip(TARGETS, inputs, strict=True):
        lines.append(
            f"// CPython v{version} ({commit}); Objects/unicodetype_db.h sha256:{sha256}"
        )
    lines += [
        "",
        "use ruff_python_ast::PythonVersion;",
        "",
        f"const VERSION_BITS: u32 = {len(TARGETS)};",
        "",
        "pub(super) fn is_printable(character: char, version: PythonVersion) -> bool {",
        "    let mask = match version {",
        "        PythonVersion::PY312 => 1,",
        "        PythonVersion::PY313 => 2,",
        "        PythonVersion::PY314 => 4,",
        "        _ => 8,",
        "    };",
        "    let codepoint = u32::from(character);",
        "    let index = RANGES.partition_point(|(start, _)| *start <= codepoint);",
        "    if index == 0 {",
        "        return false;",
        "    }",
        "    let end_and_mask = RANGES[index - 1].1;",
        "    (codepoint << VERSION_BITS) <= end_and_mask && end_and_mask & mask != 0",
        "}",
        "",
        "// Inclusive range ends store the per-version printability mask in their low bits.",
        "#[rustfmt::skip]",
        "const RANGES: &[(u32, u32)] = &[",
    ]
    lines += [
        f"    (0x{start:x}, 0x{(end << len(TARGETS)) | mask:_x}),"
        for start, end, mask in ranges
    ]
    lines += ["];", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
