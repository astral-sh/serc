"""Render pinned 3.12/3.13 metadata without changing the modern target parser."""

from __future__ import annotations

import hashlib

from legacy_opcode_metadata import (
    parse_312_metadata,
    parse_313_metadata,
    rust_stack_expression,
)

# These are semantic IR identities, independent of every release's wire IDs.
# Existing 3.14 identities occupy 0..120 and 128 and are never renumbered.
LEGACY_OPCODES = (
    "BEFORE_ASYNC_WITH",
    "BEFORE_WITH",
    "BINARY_SUBSCR",
    "BUILD_CONST_KEY_MAP",
    "ENTER_EXECUTOR",
    "FORMAT_VALUE",
    "KW_NAMES",
    "LOAD_ASSERTION_ERROR",
    "LOAD_CLOSURE",
    "RETURN_CONST",
)
LEGACY_PROPERTIES = {
    "BUILD_CONST_KEY_MAP": {"HAS_ARG_FLAG"},
    "ENTER_EXECUTOR": {"HAS_ARG_FLAG"},
    "FORMAT_VALUE": {"HAS_ARG_FLAG"},
    "KW_NAMES": {"HAS_ARG_FLAG", "HAS_CONST_FLAG"},
    "LOAD_CLOSURE": {"HAS_ARG_FLAG", "HAS_FREE_FLAG"},
    "RETURN_CONST": {"HAS_ARG_FLAG", "HAS_CONST_FLAG"},
}


def render_legacy_opcodes(metadata: dict) -> str:
    """Render the shared legacy IR identities and their semantic properties."""
    property_flags = {
        "HAS_ARG_FLAG",
        "HAS_CONST_FLAG",
        "HAS_NAME_FLAG",
        "HAS_JUMP_FLAG",
        "HAS_FREE_FLAG",
        "HAS_LOCAL_FLAG",
    }
    for name in LEGACY_OPCODES:
        if name in metadata["flags"]:
            actual = metadata["flags"][name] & property_flags
            if actual != LEGACY_PROPERTIES.get(name, set()):
                raise ValueError(
                    f"legacy semantic properties differ for {name}: {actual}"
                )
    lines = [
        "// @generated by scripts/generate_cpython_target.py; do not edit.",
        "// Semantic identities for instructions absent from the 3.14 IR baseline.",
        "",
        "use super::Opcode;",
        "",
    ]
    for code, name in enumerate(LEGACY_OPCODES, 129):
        lines.append(f"pub(crate) const {name}: Opcode = Opcode::new({code});")
    return "\n".join(lines) + "\n"


def render_legacy_target(sources: dict[str, str], g) -> str:
    metadata = (
        parse_312_metadata(sources)
        if g.TARGET_MINOR == "3.12"
        else parse_313_metadata(sources)
    )
    opcodes = metadata["opcodes"]
    names = {name for name, _ in opcodes}
    known = g.parse_opcodes_from_generated_names() | set(LEGACY_OPCODES)
    if missing := names - known:
        raise ValueError(f"target requires new semantic opcodes: {sorted(missing)}")
    patchlevel = sources["Include/patchlevel.h"]
    version = tuple(
        int(
            g.require_match(
                rf"^#define\s+PY_{part}_VERSION\s+(\d+)$", patchlevel, part
            ).group(1)
        )
        for part in ("MAJOR", "MINOR", "MICRO")
    )
    if version != g.TARGET_VERSION:
        raise ValueError(f"unexpected CPython version {version}")
    magic = int(
        g.require_match(
            r"^MAGIC_NUMBER = \((\d+)\)\.to_bytes\(2, 'little'\) \+ b'\\r\\n'$",
            sources["Lib/importlib/_bootstrap_external.py"],
            "legacy magic number",
        ).group(1)
    )
    small_ints = g.require_definitions(
        g.parse_numeric_defines(
            sources["Include/internal/pycore_global_objects.h"], "_PY_NSMALL"
        ),
        {"_PY_NSMALLNEGINTS", "_PY_NSMALLPOSINTS"},
        "small integer singleton bounds",
    )
    lines = [
        "// @generated by scripts/generate_cpython_target.py; do not edit.",
        f"// CPython {g.TARGET_TAG} ({g.TARGET_COMMIT}).",
    ]
    for relative in g.TARGET_INPUTS:
        digest = hashlib.sha256(sources[relative].encode()).hexdigest()
        lines.append(f"// {relative}: sha256:{digest}")
    startup_input, startup_digest = g.startup_input()
    startup_strings = g.read_startup_strings()
    lines.append(f"// {startup_input}: sha256:{startup_digest}")
    lines.extend(
        [
            "",
            "use super::{Opcode, opcodes};",
            "",
            f'pub(crate) const TARGET_TAG: &str = "{g.TARGET_TAG}";',
            f'pub(crate) const TARGET_COMMIT: &str = "{g.TARGET_COMMIT}";',
            'pub(crate) const TARGET_IMPLEMENTATION: &str = "cpython";',
            f"pub(crate) const TARGET_VERSION: (u8, u8, u8) = {version};",
            f"pub(crate) const TARGET_MAGIC_NUMBER: [u8; 4] = [0x{magic & 255:02x}, 0x{magic >> 8:02x}, 0x0d, 0x0a];",
            f"pub(crate) const SMALL_INT_MIN: i64 = -{small_ints['_PY_NSMALLNEGINTS']};",
            f"pub(crate) const SMALL_INT_MAX: i64 = {small_ints['_PY_NSMALLPOSINTS'] - 1};",
            "",
            "pub(crate) const fn code(opcode: Opcode) -> u8 {",
            "    match opcode {",
        ]
    )
    for name, code in opcodes:
        lines.append(f"        opcodes::{name} => {code},")
    lines.extend(
        [
            f'        _ => panic!("unsupported opcode for CPython {g.TARGET_MINOR}"),',
            "    }",
            "}",
            "",
            "pub(crate) const fn caches(opcode: Opcode) -> u8 {",
            "    match opcode {",
        ]
    )
    for name, _ in opcodes:
        if width := metadata["caches"].get(name, 0):
            lines.append(f"        opcodes::{name} => {width},")
    lines.extend(["        _ => 0,", "    }", "}", ""])
    jumps = {name for name in names if "HAS_JUMP_FLAG" in metadata["flags"][name]}
    lines.extend(
        [
            "pub(crate) const fn has_jump(opcode: Opcode) -> bool {",
            f"    {g.opcode_match_expression(opcodes, jumps)}",
            "}",
            "",
        ]
    )
    for method, classified in metadata["predicates"].items():
        if method == "is_unconditional_jump":
            continue
        lines.extend(
            [
                f"pub(crate) const fn {method}(opcode: Opcode) -> bool {{",
                f"    {g.opcode_match_expression(opcodes, classified)}",
                "}",
                "",
            ]
        )
    static_strings = g.parse_preinterned_strings(
        sources["Include/internal/pycore_global_strings.h"]
    )
    compiler_strings = g.parse_compiler_interned_strings(sources["Python/Python-ast.c"])
    for name, values in (
        ("PREINTERNED_STRINGS", static_strings),
        ("COMPILER_INTERNED_STRINGS", compiler_strings),
        ("STARTUP_INTERNED_STRINGS", startup_strings),
    ):
        if name in {"PREINTERNED_STRINGS", "COMPILER_INTERNED_STRINGS"}:
            lines.append("#[cfg(test)]")
        lines.append(f"pub(crate) static {name}: &[&str] = &[")
        lines.extend(f"    {g.rust_string_literal(value)}," for value in values)
        lines.extend(["];", ""])
    lines.extend(
        [
            "pub(crate) fn is_preinterned_string(value: &str) -> bool {",
            "    static STARTUP: std::sync::LazyLock<rustc_hash::FxHashSet<&'static str>> =",
            "        std::sync::LazyLock::new(|| STARTUP_INTERNED_STRINGS.iter().copied().collect());",
            "    is_preinterned_static_string(value)",
            '        || (cfg!(target_os = "linux") && STARTUP.contains(value))',
            "}",
            "",
        ]
    )
    # Direct C compilation does not initialize builtin compile()'s AST classes.
    lookup = g.render_preinterned_lookup(
        static_strings, (), tuple(compiler_strings), compiler_strings_on_linux=False
    )
    lookup[0] = "fn is_preinterned_static_string(value: &str) -> bool {"
    lines.extend(lookup)
    lines.extend(["", "#[allow(dead_code)]", "pub(crate) mod operands {"])
    render_operands(lines, sources, g)
    lines.extend(["}", "", "#[allow(dead_code)]", "pub(crate) mod code_flags {"])
    for name, value in g.parse_numeric_defines(
        sources["Include/cpython/code.h"], "CO_"
    ):
        if name != "CO_MAXBLOCKS":
            lines.append(f"    pub(crate) const {name}: u32 = {g.rust_hex(value, 8)};")
    lines.extend(["}", "", "#[allow(dead_code)]", "pub(crate) mod local_kinds {"])
    for name, value in g.parse_numeric_defines(
        sources["Include/internal/pycore_code.h"], "CO_FAST_"
    ):
        lines.append(f"    pub(crate) const {name}: u8 = {g.rust_hex(value, 2)};")
    lines.extend(
        [
            "}",
            "",
            "pub(crate) fn stack_counts(opcode: Opcode, argument: u32) -> (usize, usize) {",
            "    let argument = i64::from(argument);",
            "    let (popped, pushed) = match opcode {",
        ]
    )
    for name, _ in opcodes:
        popped = rust_stack_expression(metadata["popped"][name])
        pushed = rust_stack_expression(metadata["pushed"][name])
        lines.append(f"        opcodes::{name} => ({popped}, {pushed}),")
    lines.extend(
        [
            '        _ => unreachable!("missing generated stack metadata for opcode {}", opcode.code()),',
            "    };",
            "    (",
            '        usize::try_from(popped).expect("negative generated stack-popped count"),',
            '        usize::try_from(pushed).expect("negative generated stack-pushed count"),',
            "    )",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def render_operands(lines: list[str], sources: dict[str, str], g) -> None:
    intrinsic = sources["Include/internal/pycore_intrinsics.h"]
    for type_name, marker, limit in (
        ("UnaryIntrinsic", "/* Unary Functions: */", "MAX_INTRINSIC_1"),
        ("BinaryIntrinsic", "/* Binary Functions: */", "MAX_INTRINSIC_2"),
    ):
        section = intrinsic.split(marker, 1)[1].split(limit, 1)[0]
        values = [
            (name, value)
            for name, value in g.parse_numeric_defines(section, "INTRINSIC_")
            if not name.endswith("_INVALID")
        ]
        g.render_operand_type(lines, type_name, values, "INTRINSIC_")
    binary = [
        (name, value)
        for name, value in g.parse_numeric_defines(sources["Include/opcode.h"], "NB_")
        if name != "NB_OPARG_LAST"
    ]
    g.render_operand_type(lines, "BinaryOperation", binary, "NB_")
    lines.extend(
        [
            "    impl BinaryOperation {",
            "        pub(crate) const fn inplace(self) -> Self {",
            "            match self {",
        ]
    )
    for name, _ in binary:
        operation = name.removeprefix("NB_")
        if not operation.startswith("INPLACE_"):
            if f"NB_INPLACE_{operation}" not in dict(binary):
                raise ValueError(f"missing in-place operation for {name}")
            lines.append(
                f"                Self::{operation} => Self::INPLACE_{operation},"
            )
    lines.extend(
        ["                _ => self,", "            }", "        }", "    }", ""]
    )
    codegen = sources["Python/compile.c"]
    shift = int(
        g.require_match(
            r"COMPARE_OP, \(cmp << (\d+)\) \| compare_masks\[cmp\]",
            codegen,
            "comparison shift",
        ).group(1)
    )
    rich = dict(g.parse_numeric_defines(sources["Include/object.h"], "Py_"))
    masks = dict(
        g.parse_numeric_defines(
            sources["Include/internal/pycore_code.h"], "COMPARISON_"
        )
    )
    less, equal, greater, unordered = (
        masks[f"COMPARISON_{name}"]
        for name in ("LESS_THAN", "EQUALS", "GREATER_THAN", "UNORDERED")
    )
    operations = [
        (name, rich[f"Py_{name}"] << shift | mask)
        for name, mask in (
            ("LT", less),
            ("LE", less | equal),
            ("EQ", equal),
            ("NE", less | greater | unordered),
            ("GT", greater),
            ("GE", greater | equal),
        )
    ]
    g.render_operand_type(lines, "ComparisonOperation", operations, "")
    lines.append(f"    pub(crate) const COMPARISON_SHIFT: u32 = {shift};")
    if g.TARGET_MINOR == "3.13":
        boolean_mask = int(
            g.require_match(
                r"INSTR_SET_OP1\([^\n]+COMPARE_OP, oparg \| (\d+)\);",
                sources["Python/flowgraph.c"],
                "comparison boolean mask",
            ).group(1)
        )
        lines.extend(
            [
                "    impl ComparisonOperation {",
                "        pub(crate) const fn boolean_argument(self) -> u32 {",
                f"            self.0 | {boolean_mask}",
                "        }",
                "        pub(crate) const fn force_boolean(argument: u32) -> u32 {",
                f"            argument | {boolean_mask}",
                "        }",
                "    }",
            ]
        )
    opcode_utils = sources["Include/internal/pycore_opcode_utils.h"]
    if attributes := g.parse_numeric_defines(opcode_utils, "MAKE_FUNCTION_"):
        g.render_operand_type(lines, "FunctionAttribute", attributes, "MAKE_FUNCTION_")
    if resume := g.parse_numeric_defines(opcode_utils, "RESUME_"):
        locations = [
            (name, value) for name, value in resume if not name.endswith("_MASK")
        ]
        g.render_operand_type(lines, "ResumeLocation", locations, "RESUME_")
        values = dict(resume)
        lines.extend(
            [
                "    impl ResumeLocation {",
                "        pub(crate) const fn at_depth(self, depth_one: bool) -> u32 {",
                f"            (self.0 & {values['RESUME_OPARG_LOCATION_MASK']})",
                f"                | if depth_one {{ {values['RESUME_OPARG_DEPTH1_MASK']} }} else {{ 0 }}",
                "        }",
                "    }",
            ]
        )
    conversion = [
        (name, value)
        for name, value in g.parse_numeric_defines(sources["Include/ceval.h"], "FVC_")
        if name != "FVC_MASK"
    ]
    g.render_operand_type(lines, "Conversion", conversion, "FVC_")
    format_values = [(name.removeprefix("FVC_"), value) for name, value in conversion]
    format_values.extend(
        (name.removeprefix("FVS_"), value)
        for name, value in g.parse_numeric_defines(sources["Include/ceval.h"], "FVS_")
        if name != "FVS_MASK"
    )
    g.render_operand_type(lines, "FormatValue", format_values, "")
